#!/usr/bin/env python3
# Compiles GNM renderer shaders (ref/gl/ps4/shaders) into a C file:
# GLSL -> SPIR-V (glslang) -> PS4 shader binary (opengnm-psbc,
# see scripts/ps4/psbc/build.sh).
#
# Runs from ref/gl/wscript when glslang and psbc are given to configure
# (--ps4-glslang, --ps4-psbc). Without them ref/gl/ps4/gnm_shaders.c, generated
# by this script and kept in the repository, is used.
#
# Usage: compile_shaders.py --glslang PATH --psbc PATH --shaders DIR -o OUTPUT.c
# SPDX-License-Identifier: MIT
# Copyright (c) 2026 Xash3D FWGS contributors

import argparse
import os
import subprocess
import sys
import tempfile

VS_COUNT = 8   # attribute mask, bit 0 - color, 1 - texcoord0, 2 - texcoord1
PS_COUNT = 32  # attribute mask as above, bit 3 - alpha test, bit 4 - fog

STAGES = {'vert': 'vertex', 'frag': 'fragment'}

def run(cmd):
	r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, universal_newlines=True)
	if r.returncode != 0:
		sys.stderr.write(r.stdout)
		sys.exit(1)

def c_array(name, data):
	out = ['static const uint8_t %s[%d] __attribute__((aligned(16))) =\n{' % (name, len(data))]
	for i in range(0, len(data), 16):
		out.append('\t' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
	out.append('};\n')
	return '\n'.join(out)

def main():
	ap = argparse.ArgumentParser()
	ap.add_argument('--glslang', required=True)
	ap.add_argument('--psbc', required=True)
	ap.add_argument('--shaders', required=True, help='directory with GLSL sources')
	ap.add_argument('-o', '--output', required=True)
	args = ap.parse_args()

	arrays = []

	with tempfile.TemporaryDirectory() as tmp:
		def compile(src, stage, name, defines=()):
			spv = os.path.join(tmp, name + '.spv')
			sb = os.path.join(tmp, name + '.sb')

			run([args.glslang, '-V', '-S', stage, *defines, os.path.join(args.shaders, src), '-o', spv])
			# -4: PS4 base GPU (GFX7), also runs on PS4 Pro
			run([args.psbc, '-s', STAGES[stage], '-f', spv, '-o', sb, '-4'])

			with open(sb, 'rb') as f:
				arrays.append(c_array(name, f.read()))

		compile('clear.vert.glsl', 'vert', 'clear_vs')
		compile('clear.frag.glsl', 'frag', 'clear_ps')

		for v in range(VS_COUNT):
			compile('gl2.vert.glsl', 'vert', 'gl2_vs_%d' % v, [
				'-DATTR_COLOR=%d' % (v & 1),
				'-DATTR_TEXCOORD0=%d' % ((v >> 1) & 1),
				'-DATTR_TEXCOORD1=%d' % ((v >> 2) & 1)])

		for f in range(PS_COUNT):
			compile('gl2.frag.glsl', 'frag', 'gl2_ps_%d' % f, [
				'-DATTR_COLOR=%d' % (f & 1),
				'-DATTR_TEXCOORD0=%d' % ((f >> 1) & 1),
				'-DATTR_TEXCOORD1=%d' % ((f >> 2) & 1),
				'-DFEAT_ALPHA_TEST=%d' % ((f >> 3) & 1),
				'-DFEAT_FOG=%d' % ((f >> 4) & 1)])

	out = [
		'// Generated by scripts/ps4/gnm/compile_shaders.py from ref/gl/ps4/shaders, do not edit',
		'#include <stdint.h>',
		'#include "gnm_shaders.h"',
		'',
	]
	out += arrays
	out.append('const gnm_shader_blob_t gnm_shader_clear_vs = { clear_vs, sizeof( clear_vs ) };')
	out.append('const gnm_shader_blob_t gnm_shader_clear_ps = { clear_ps, sizeof( clear_ps ) };')
	out.append('')
	out.append('const gnm_shader_blob_t gnm_shader_gl2_vs[GNM_GL2_VS_COUNT] =\n{')
	out += ['\t{ gl2_vs_%d, sizeof( gl2_vs_%d ) },' % (i, i) for i in range(VS_COUNT)]
	out.append('};')
	out.append('')
	out.append('const gnm_shader_blob_t gnm_shader_gl2_ps[GNM_GL2_PS_COUNT] =\n{')
	out += ['\t{ gl2_ps_%d, sizeof( gl2_ps_%d ) },' % (i, i) for i in range(PS_COUNT)]
	out.append('};')

	with open(args.output, 'w') as f:
		f.write('\n'.join(out) + '\n')

if __name__ == '__main__':
	main()
